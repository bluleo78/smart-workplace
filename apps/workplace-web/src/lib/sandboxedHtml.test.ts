import { describe, expect, it } from 'vitest'

import cases from './htmlHasScripts.cases.json'
import { htmlHasScripts, LINK_TARGET_BASE, SANDBOX_HEAD, THIN_SCROLLBAR_STYLE, withSandboxHead } from './sandboxedHtml'

describe('withSandboxHead', () => {
  it('DOCTYPE 이 있으면 그 뒤에 주입해 표준 모드를 유지한다', () => {
    const html = '<!DOCTYPE html><html><body>본문</body></html>'
    const out = withSandboxHead(html)
    expect(out.startsWith('<!DOCTYPE html>' + SANDBOX_HEAD)).toBe(true)
    expect(out.endsWith('<html><body>본문</body></html>')).toBe(true)
  })

  it('BOM·공백·소문자 DOCTYPE 도 인식한다', () => {
    const html = '\uFEFF\n  <!doctype html>\n<p>x</p>'
    expect(withSandboxHead(html)).toBe('\uFEFF\n  <!doctype html>' + SANDBOX_HEAD + '\n<p>x</p>')
  })

  it('DOCTYPE 앞의 주석·XML 선언은 건너뛰고 DOCTYPE 뒤에 주입한다', () => {
    const commented = '<!-- generated by X -->\n<!DOCTYPE html><p>x</p>'
    expect(withSandboxHead(commented)).toBe(
      '<!-- generated by X -->\n<!DOCTYPE html>' + SANDBOX_HEAD + '<p>x</p>',
    )
    const xhtml = '<?xml version="1.0"?>\n<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0//EN"><html/>'
    expect(withSandboxHead(xhtml)).toBe(
      '<?xml version="1.0"?>\n<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0//EN">' + SANDBOX_HEAD + '<html/>',
    )
  })

  it('앞 공백이 길고 DOCTYPE 이 없어도 즉시 끝난다(지수 백트래킹 회귀 가드)', () => {
    const html = '\n'.repeat(5000) + '<p>조각</p>'
    const t0 = performance.now()
    expect(withSandboxHead(html)).toBe(SANDBOX_HEAD + html)
    expect(performance.now() - t0).toBeLessThan(100)
  })

  it('주석이 길게 이어지고 DOCTYPE 이 없어도 즉시 끝난다(지수 백트래킹 회귀 가드)', () => {
    const html = '<!---->'.repeat(2000) + '<!--a-->'.repeat(2000) + '<p>메일</p>'
    const t0 = performance.now()
    expect(withSandboxHead(html)).toBe(SANDBOX_HEAD + html)
    expect(performance.now() - t0).toBeLessThan(100)
  })

  it('주석이 여러 개 앞서도 그 뒤 DOCTYPE 을 찾는다', () => {
    const html = '<!--a--> <!--b-->\n<!doctype html><p>x</p>'
    expect(withSandboxHead(html)).toBe('<!--a--> <!--b-->\n<!doctype html>' + SANDBOX_HEAD + '<p>x</p>')
  })

  it('닫히지 않은 주석·DOCTYPE 이면 맨 앞에 주입한다', () => {
    expect(withSandboxHead('<!-- 열림만')).toBe(SANDBOX_HEAD + '<!-- 열림만')
    expect(withSandboxHead('<!DOCTYPE html')).toBe(SANDBOX_HEAD + '<!DOCTYPE html')
  })

  it('DOCTYPE 이 없으면 맨 앞에 주입한다', () => {
    expect(withSandboxHead('<p>조각</p>')).toBe(SANDBOX_HEAD + '<p>조각</p>')
  })

  it('본문 중간의 doctype 문자열은 건드리지 않는다', () => {
    const html = '<p>예: <!DOCTYPE html></p>'
    expect(withSandboxHead(html)).toBe(SANDBOX_HEAD + html)
  })

  it('주입 내용은 링크 base 와 스타일뿐이다(스크립트 없음)', () => {
    expect(SANDBOX_HEAD).not.toMatch(/<script/i)
    // WP-427: 링크는 새 탭으로 — href 는 두지 않아 상대 경로 해석을 바꾸지 않는다.
    expect(SANDBOX_HEAD.startsWith(LINK_TARGET_BASE)).toBe(true)
    expect(LINK_TARGET_BASE).not.toMatch(/href/i)
    expect(THIN_SCROLLBAR_STYLE).toContain('*{scrollbar-width:thin}')
    // 상속되는 색은 :root 에만 — 문서가 body 등에 준 scrollbar-color 상속을 끊지 않는다.
    expect(THIN_SCROLLBAR_STYLE).not.toMatch(/\*\{[^}]*scrollbar-color/)
  })
})

// WP-1260: 미리보기 「스크립트 실행」 단추를 보일지 고르는 판정.
describe('htmlHasScripts', () => {
  it('script 요소가 있으면 참이다(대소문자·속성·자기 닫기 무관)', () => {
    expect(htmlHasScripts('<html><body><script>fit()</script></body></html>')).toBe(true)
    expect(htmlHasScripts('<SCRIPT type="module">x</SCRIPT>')).toBe(true)
    expect(htmlHasScripts('<script/>')).toBe(true)
  })

  it('태그 안 인라인 이벤트가 있으면 참이다', () => {
    expect(htmlHasScripts('<button onclick="go()">이동</button>')).toBe(true)
    expect(htmlHasScripts('<body\nonload = "init()">')).toBe(true)
  })

  it('javascript: 주소가 있으면 참이다', () => {
    expect(htmlHasScripts('<a href="javascript:next()">다음</a>')).toBe(true)
    expect(htmlHasScripts("<a href = ' JavaScript:go()'>")).toBe(true)
  })

  it('스크립트가 없는 문서는 거짓이다', () => {
    expect(htmlHasScripts('<!doctype html><html><body><h1>안녕 HTML</h1></body></html>')).toBe(false)
    // 비슷한 이름(scripts 태그·noscript 아님)·본문 글자 on=·data-on 속성은 스크립트가 아니다.
    expect(htmlHasScripts('<scripts>목록</scripts><p>switch on = 켜기</p><div data-onclick="x"></div>')).toBe(false)
  })

  it('수 MB 문서도 즉시 판정한다(백트래킹 회귀 가드)', () => {
    const big = '<img src="data:image/png;base64,' + 'A'.repeat(3_000_000) + '">' + '<p>'.repeat(200_000)
    const start = performance.now()
    expect(htmlHasScripts(big)).toBe(false)
    expect(performance.now() - start).toBeLessThan(1000)
  })
})

