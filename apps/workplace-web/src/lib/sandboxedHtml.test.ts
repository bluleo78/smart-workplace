import { describe, expect, it } from 'vitest'

import cases from './htmlHasScripts.cases.json'
import {
  buildSandboxDoc,
  htmlHasScripts,
  IN_PAGE_LINK_SCRIPT,
  LINK_TARGET_BASE,
  ownScriptsCsp,
  rewriteInPageLinks,
  SANDBOX_HEAD,
  SCRIPT_SANDBOX_HEAD,
  THIN_SCROLLBAR_STYLE,
  withSandboxHead,
  withScriptNonce,
} from './sandboxedHtml'

describe('withSandboxHead', () => {
  it('DOCTYPE 이 있으면 그 뒤에 주입해 표준 모드를 유지한다', () => {
    const html = '<!DOCTYPE html><html><body>본문</body></html>'
    const out = withSandboxHead(html)
    expect(out.startsWith('<!DOCTYPE html>' + SANDBOX_HEAD)).toBe(true)
    expect(out.endsWith('<html><body>본문</body></html>')).toBe(true)
  })

  it('BOM·공백·소문자 DOCTYPE 도 인식한다', () => {
    const html = '\uFEFF\n  <!doctype html>\n<p>x</p>'
    expect(withSandboxHead(html)).toBe('\uFEFF\n  <!doctype html>' + SANDBOX_HEAD + '\n<p>x</p>')
  })

  it('DOCTYPE 앞의 주석·XML 선언은 건너뛰고 DOCTYPE 뒤에 주입한다', () => {
    const commented = '<!-- generated by X -->\n<!DOCTYPE html><p>x</p>'
    expect(withSandboxHead(commented)).toBe(
      '<!-- generated by X -->\n<!DOCTYPE html>' + SANDBOX_HEAD + '<p>x</p>',
    )
    const xhtml = '<?xml version="1.0"?>\n<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0//EN"><html/>'
    expect(withSandboxHead(xhtml)).toBe(
      '<?xml version="1.0"?>\n<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0//EN">' + SANDBOX_HEAD + '<html/>',
    )
  })

  it('앞 공백이 길고 DOCTYPE 이 없어도 즉시 끝난다(지수 백트래킹 회귀 가드)', () => {
    const html = '\n'.repeat(5000) + '<p>조각</p>'
    const t0 = performance.now()
    expect(withSandboxHead(html)).toBe(SANDBOX_HEAD + html)
    expect(performance.now() - t0).toBeLessThan(100)
  })

  it('주석이 길게 이어지고 DOCTYPE 이 없어도 즉시 끝난다(지수 백트래킹 회귀 가드)', () => {
    const html = '<!---->'.repeat(2000) + '<!--a-->'.repeat(2000) + '<p>메일</p>'
    const t0 = performance.now()
    expect(withSandboxHead(html)).toBe(SANDBOX_HEAD + html)
    expect(performance.now() - t0).toBeLessThan(100)
  })

  it('주석이 여러 개 앞서도 그 뒤 DOCTYPE 을 찾는다', () => {
    const html = '<!--a--> <!--b-->\n<!doctype html><p>x</p>'
    expect(withSandboxHead(html)).toBe('<!--a--> <!--b-->\n<!doctype html>' + SANDBOX_HEAD + '<p>x</p>')
  })

  it('닫히지 않은 주석·DOCTYPE 이면 맨 앞에 주입한다', () => {
    expect(withSandboxHead('<!-- 열림만')).toBe(SANDBOX_HEAD + '<!-- 열림만')
    expect(withSandboxHead('<!DOCTYPE html')).toBe(SANDBOX_HEAD + '<!DOCTYPE html')
  })

  it('DOCTYPE 이 없으면 맨 앞에 주입한다', () => {
    expect(withSandboxHead('<p>조각</p>')).toBe(SANDBOX_HEAD + '<p>조각</p>')
  })

  it('본문 중간의 doctype 문자열은 건드리지 않는다', () => {
    const html = '<p>예: <!DOCTYPE html></p>'
    expect(withSandboxHead(html)).toBe(SANDBOX_HEAD + html)
  })

  it('주입 내용은 링크 base 와 스타일뿐이다(스크립트 없음)', () => {
    expect(SANDBOX_HEAD).not.toMatch(/<script/i)
    // WP-427: 링크는 새 탭으로 — href 는 두지 않아 상대 경로 해석을 바꾸지 않는다.
    expect(SANDBOX_HEAD.startsWith(LINK_TARGET_BASE)).toBe(true)
    expect(LINK_TARGET_BASE).not.toMatch(/href/i)
    expect(THIN_SCROLLBAR_STYLE).toContain('*{scrollbar-width:thin}')
    // 상속되는 색은 :root 에만 — 문서가 body 등에 준 scrollbar-color 상속을 끊지 않는다.
    expect(THIN_SCROLLBAR_STYLE).not.toMatch(/\*\{[^}]*scrollbar-color/)
  })
})

// WP-1271: 목차 같은 문서 안 이동 링크가 새 탭에 앱을 다시 열지 않고 그 문서 안에서 움직이게 한다.
describe('rewriteInPageLinks', () => {
  it('target 없는 # 링크를 about:srcdoc 조각 + _self 로 바꾼다(큰·작은따옴표·따옴표 없음)', () => {
    expect(rewriteInPageLinks('<a href="#summary">요약</a>')).toBe('<a target="_self" href="about:srcdoc#summary">요약</a>')
    expect(rewriteInPageLinks("<a class='toc' href='#s-2'>2</a>")).toBe(
      `<a target="_self" class='toc' href='about:srcdoc#s-2'>2</a>`,
    )
    expect(rewriteInPageLinks('<A HREF=#top>위로</A>')).toBe('<A target="_self" HREF="about:srcdoc#top">위로</A>')
  })

  it('area 와 빈 조각(#)·앞 공백도 바꾼다', () => {
    expect(rewriteInPageLinks('<area shape="rect" href="#map1" />')).toBe(
      '<area target="_self" shape="rect" href="about:srcdoc#map1" />',
    )
    expect(rewriteInPageLinks('<a href="#">맨 위</a>')).toBe('<a target="_self" href="about:srcdoc#">맨 위</a>')
    expect(rewriteInPageLinks('<a href=" #x">x</a>')).toBe('<a target="_self" href="about:srcdoc#x">x</a>')
  })

  it('빈 target 은 없는 것으로 보고 바꾼다 — 브라우저도 그때 <base target> 을 따른다', () => {
    expect(rewriteInPageLinks('<a href="#x" target="">x</a>')).toBe('<a target="_self" href="about:srcdoc#x" target="">x</a>')
    expect(rewriteInPageLinks("<a target=' ' href='#x'>x</a>")).toBe(`<a target="_self" target=' ' href='about:srcdoc#x'>x</a>`)
  })

  it('SVG 링크의 xlink:href 도 바꾼다', () => {
    expect(rewriteInPageLinks('<a xlink:href="#node3"><rect/></a>')).toBe('<a target="_self" xlink:href="about:srcdoc#node3"><rect/></a>')
  })

  it('외부·상대 링크와 target 을 직접 단 링크는 그대로 둔다(WP-427 새 탭 유지)', () => {
    const untouched = [
      '<a href="https://example.com/#x">밖</a>',
      '<a href="page.html#x">상대</a>',
      '<a href="/root">루트</a>',
      '<a href="#x" target="_blank">명시</a>',
      '<a target=_top href="#x">명시</a>',
      '<a name="anchor">이름만</a>',
      '<abbr title="#x">약어</abbr>',
      '<a title="href=#x" href="https://e.com">값 속 글자</a>',
    ]
    for (const html of untouched) expect(rewriteInPageLinks(html)).toBe(html)
  })

  it('href 가 두 번이면 첫 것만 본다(HTML 파서와 같다)', () => {
    expect(rewriteInPageLinks('<a href="https://e.com" href="#x">a</a>')).toBe('<a href="https://e.com" href="#x">a</a>')
    expect(rewriteInPageLinks('<a href="#x" href="https://e.com">a</a>')).toBe(
      '<a target="_self" href="about:srcdoc#x" href="https://e.com">a</a>',
    )
  })

  it('여러 링크가 섞인 문서에서 # 링크만 바꾼다', () => {
    const html = '<nav><a href="#a">A</a> <a href="https://e.com">E</a></nav><h2 id="a">A</h2>'
    expect(rewriteInPageLinks(html)).toBe(
      '<nav><a target="_self" href="about:srcdoc#a">A</a> <a href="https://e.com">E</a></nav><h2 id="a">A</h2>',
    )
  })

  it('닫히지 않은 태그가 길게 이어져도 즉시 끝난다(백트래킹 회귀 가드)', () => {
    const html = '<a '.repeat(10000) + 'href="#x"'
    const t0 = performance.now()
    expect(rewriteInPageLinks(html)).toBe(html)
    const attrs = '<a ' + ' x="1"'.repeat(10000) + ' href="#y">'
    expect(rewriteInPageLinks(attrs)).toContain('href="about:srcdoc#y"')
    expect(performance.now() - t0).toBeLessThan(500)
  })
})

describe('buildSandboxDoc', () => {
  const html = '<!doctype html><a href="#s">목차</a><h2 id="s">절</h2>'

  it('스크립트 꺼짐이면 링크를 바꾸고 스크립트 없는 기본 머리말만 넣는다', () => {
    const doc = buildSandboxDoc(html, false)
    expect(doc).toBe('<!doctype html>' + SANDBOX_HEAD + '<a target="_self" href="about:srcdoc#s">목차</a><h2 id="s">절</h2>')
    expect(doc).not.toMatch(/<script/i)
  })

  it('스크립트 켜짐이면 href 는 그대로 두고 문서 안 이동 처리기를 넣는다', () => {
    const doc = buildSandboxDoc(html, true)
    expect(doc).toBe('<!doctype html>' + SCRIPT_SANDBOX_HEAD + '<a href="#s">목차</a><h2 id="s">절</h2>')
    expect(SCRIPT_SANDBOX_HEAD.endsWith(IN_PAGE_LINK_SCRIPT)).toBe(true)
  })

  it('우리 스크립트는 스크립트 켜짐일 때만 문서 뒤에 붙인다', () => {
    const own = '<script data-own>x()</script>'
    expect(buildSandboxDoc(html, true, { script: own })).toBe('<!doctype html>' + SCRIPT_SANDBOX_HEAD + '<a href="#s">목차</a><h2 id="s">절</h2>' + own)
    expect(buildSandboxDoc(html, false, { script: own })).not.toContain('data-own')
  })

  // WP-1290 × WP-1309 — 노트 스크립트가 멈춘 채 편집 도구만 돌리는 문서.
  it('nonce 가 있으면 맨 앞 CSP 로 문서 스크립트를 막고 우리 스크립트(문서 안 이동·own)에만 nonce 를 단다', () => {
    const page = '<!doctype html><p onclick="evil()">글</p><script>evil()</script>'
    const doc = buildSandboxDoc(page, true, { script: '<script data-own>ok()</script>', nonce: 'abc123' })
    expect(doc.startsWith('<!doctype html>' + ownScriptsCsp('abc123'))).toBe(true)
    expect(ownScriptsCsp('abc123')).toContain(`script-src 'nonce-abc123'`)
    expect(ownScriptsCsp('abc123')).toContain(`object-src 'none'`)
    expect(doc).toContain('<script data-in-page-links nonce="abc123">')
    expect(doc.endsWith('<script data-own nonce="abc123">ok()</script>')).toBe(true)
    // 문서 자신의 스크립트에는 nonce 를 달지 않는다.
    expect(doc).toContain('<script>evil()</script>')
  })

  it('withScriptNonce 는 여는 태그마다 nonce 를 끝에 단다', () => {
    expect(withScriptNonce('<script>a</script><script data-x>b</script>', 'n')).toBe('<script nonce="n">a</script><script data-x nonce="n">b</script>')
  })
})

// WP-1260: 미리보기 「스크립트 실행」 단추를 보일지 고르는 판정.
describe('htmlHasScripts', () => {
  it('script 요소가 있으면 참이다(대소문자·속성·자기 닫기 무관)', () => {
    expect(htmlHasScripts('<html><body><script>fit()</script></body></html>')).toBe(true)
    expect(htmlHasScripts('<SCRIPT type="module">x</SCRIPT>')).toBe(true)
    expect(htmlHasScripts('<script/>')).toBe(true)
  })

  it('태그 안 인라인 이벤트가 있으면 참이다', () => {
    expect(htmlHasScripts('<button onclick="go()">이동</button>')).toBe(true)
    expect(htmlHasScripts('<body\nonload = "init()">')).toBe(true)
  })

  it('javascript: 주소가 있으면 참이다', () => {
    expect(htmlHasScripts('<a href="javascript:next()">다음</a>')).toBe(true)
    expect(htmlHasScripts("<a href = ' JavaScript:go()'>")).toBe(true)
  })

  it('스크립트가 없는 문서는 거짓이다', () => {
    expect(htmlHasScripts('<!doctype html><html><body><h1>안녕 HTML</h1></body></html>')).toBe(false)
    // 비슷한 이름(scripts 태그·noscript 아님)·본문 글자 on=·data-on 속성은 스크립트가 아니다.
    expect(htmlHasScripts('<scripts>목록</scripts><p>switch on = 켜기</p><div data-onclick="x"></div>')).toBe(false)
  })

  it('수 MB 문서도 즉시 판정한다(백트래킹 회귀 가드)', () => {
    const big = '<img src="data:image/png;base64,' + 'A'.repeat(3_000_000) + '">' + '<p>'.repeat(200_000)
    const start = performance.now()
    expect(htmlHasScripts(big)).toBe(false)
    expect(performance.now() - start).toBeLessThan(1000)
  })
})

