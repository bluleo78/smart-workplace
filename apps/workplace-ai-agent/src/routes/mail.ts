/**
 * WP-1341 분류 교정 학습 — 사용자가 메뉴로 분류를 바꾼 뒤 API 가 부른다. 새 라우트라 구 ai-agent 에선 404 이고 API 는 학습을 NONE 으로 처리한다.
 * toCategory 는 5종만(400), 기억은 API 가 최대 50개를 고른다(넘으면 400). fromCategory·senderIsMember·memories 는 생략해도 된다.
 */
export const learnCategorySchema = z.object({
  subject: z.string(),
  from: z.string(),
  bodyHead: z.string(),
  fromCategory: z.string().nullish(),
  toCategory: mailCategoryInput,
  senderIsMember: z.boolean().default(false),
  memories: z
    .array(z.object({ id: z.number().int().positive(), content: z.string() }))
    .max(50)
    .default([]),
  ...baseConfig,
});

// 공통 핸들러 팩토리 — zod 검증 → 러너 호출 → 400/200/503/502 응답.
// 제공자 장애로 판정되면 일반 실패(502)와 구분해 503 + reason 을 내려, 호출 측이 재시도·안내를 달리할 수 있게 한다(WP-1347). drive 등 타 라우터에서도 재사용.
export function handler<T>(
  schema: z.ZodType<T>,
  run: (input: T, deps: RunAgentDeps) => Promise<unknown>,
  deps: RunAgentDeps,
  tag: string,
) {
  return async (req: Request, res: Response): Promise<void> => {
    const parsed = schema.safeParse(req.body);
    if (!parsed.success) {
      res.status(400).json({ error: 'invalid_payload', issues: parsed.error.issues });
      return;
    }
    try {
      res.status(200).json(await run(parsed.data, deps));
    } catch (e) {
      const message = e instanceof Error ? e.message : String(e);
      const reason = classifyProviderError(e);
      if (reason) {
        console.warn(`[${tag}] 제공자 장애(${reason}):`, message);
        res.status(503).json({ error: `${tag}_unavailable`, reason });
        return;
      }
      console.error(`[${tag}] 실패:`, message);
      res.status(502).json({ error: `${tag}_failed` });
    }
  };
}

export function createMailRouter(deps: RunAgentDeps): Router {
  const router = Router();

  // WP-149 ③ 원본 분석: {category, summary} — 원본별 1회(공통 비서).
  router.post('/mail/analyze-content', handler(analyzeContentSchema, runMailAnalyzeContent, deps, 'mail-analyze-content'));
  router.post('/mail/classify-batch', handler(classifyBatchSchema, runMailClassifyBatch, deps, 'mail-classify-batch'));
  // WP-149 ④ 개인 분석: {needsReply, personalSummary, personalSummaryValid, category, personalCategory(WP-1341)} — 사본별 1회(개인→공통 비서).
  router.post('/mail/analyze-personal', handler(analyzePersonalSchema, runMailAnalyzePersonal, deps, 'mail-analyze-personal'));

  // WP-1341 분류 교정 학습: {action: CREATE|UPDATE|NONE, memoryId, content}.
  router.post('/mail/learn-category', handler(learnCategorySchema, runMailLearnCategory, deps, 'mail-learn-category'));

  // 답장 초안 생성: draft 텍스트 반환.
  router.post('/mail/reply-draft', handler(replyDraftSchema, runMailReplyDraft, deps, 'mail-reply-draft'));
  // WP-576 새 메일 초안: subject(제목이 비었을 때만) + body(평문) 반환.
  router.post('/mail/compose-draft', handler(composeDraftSchema, runMailComposeDraft, deps, 'mail-compose-draft'));
  // 초안 코칭: notes + improvedBodyHtml 반환.
  router.post('/mail/draft-coaching', handler(coachDraftSchema, runMailDraftCoaching, deps, 'mail-draft-coaching'));
  // #520 메일→이슈 초안: title/body/priority/projectKey 반환.
  router.post('/mail/issue-draft', handler(issueDraftSchema, runMailIssueDraft, deps, 'mail-issue-draft'));

  return router;
}
