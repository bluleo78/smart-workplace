describe('buildPersonalUserMessage — WP-150 보강 블록', () => {
  const full = {
    ...cfg,
    subject: '배포 일정 확인 부탁드립니다',
    fromAddress: 'minsu@acme.com',
    fromName: '김민수',
    body: '금요일까지 확인 부탁드립니다',
    autoGenerated: false,
    me: {
      addresses: ['gd@acme.com', 'gd@gmail.com'],
      name: '홍길동',
      otherNames: ['Gildong Hong'],
      title: '팀장',
      groups: ['개발팀'],
    },
    recipient: { myRole: 'TO' as const, toCount: 1, ccCount: 3 },
    sender: {
      relation: 'MEMBER' as const,
      name: '김민수',
      title: '팀장',
      organization: null,
      sameGroups: ['개발팀'],
      favorite: true,
    },
    thread: [
      { fromMe: false, from: '김민수 <minsu@acme.com>', date: '2026-09-29T01:00Z', body: '스테이징 검증 끝났습니다' },
      { fromMe: true, from: 'gd@acme.com', date: '2026-09-30T02:00Z', body: '운영 날짜는요?' },
    ],
    linkedIssue: { key: 'WP-12', title: '배포 일정 확정', status: 'IN_PROGRESS' },
    attachments: ['일정표.xlsx'],
    includeNeedsReply: true,
    includePersonalSummary: true,
    includeCategory: false,
  };

  it('스펙 순서로 모든 블록을 조립', () => {
    expect(buildPersonalUserMessage(full)).toBe(
      '[나] 홍길동 (다른 이름: Gildong Hong) · 팀장 · 소속: 개발팀\n' +
        '     주소: gd@acme.com, gd@gmail.com\n' +
        '[보낸 사람] 김민수 <minsu@acme.com> — 사내 구성원 · 같은 조직(개발팀) · 팀장 · 즐겨찾기\n' +
        '[받는 사람] 나는 To · To 1명 · CC 3명\n' +
        '[제목] 배포 일정 확인 부탁드립니다\n' +
        '[본문]\n금요일까지 확인 부탁드립니다\n' +
        '[이전 메일] 같은 스레드의 직전 메일(오래된 순)\n' +
        '--- 김민수 <minsu@acme.com> · 2026-09-29T01:00Z\n스테이징 검증 끝났습니다\n' +
        '--- 나 · 2026-09-30T02:00Z\n운영 날짜는요?\n' +
        '[연결 이슈] WP-12 배포 일정 확정 (진행 중)\n' +
        '[첨부] 일정표.xlsx',
    );
  });

  it('외부 연락처 · 알 수 없는 외부 · 나 자신 표기', () => {
    const contact = buildPersonalUserMessage({
      ...full,
      sender: { relation: 'CONTACT', name: 'Jane', title: '과장', organization: 'ACME', sameGroups: null, favorite: false },
    });
    expect(contact).toContain('[보낸 사람] 김민수 <minsu@acme.com> — 외부 연락처 · ACME · 과장\n');
    expect(buildPersonalUserMessage({ ...full, sender: { relation: 'UNKNOWN' } })).toContain(
      '[보낸 사람] 김민수 <minsu@acme.com> — 알 수 없는 외부\n',
    );
    expect(buildPersonalUserMessage({ ...full, sender: { relation: 'SELF' } })).toContain(
      '[보낸 사람] 김민수 <minsu@acme.com> — 나 자신\n',
    );
  });

  it('헤더에 보낸 사람 이름이 없으면 관계의 이름을 쓴다', () => {
    const msg = buildPersonalUserMessage({
      ...full,
      fromName: '',
      sender: { relation: 'MEMBER', name: '김민수', title: null, organization: null, sameGroups: [], favorite: false },
    });
    expect(msg).toContain('[보낸 사람] 김민수 <minsu@acme.com> — 사내 구성원\n');
  });

  it('구버전 입력(보강 필드 없음·null)은 WP-149 와 같은 메시지', () => {
    const legacy = {
      ...full,
      me: { addresses: ['gd@acme.com', 'gd@gmail.com'], name: null, otherNames: null, title: null, groups: null },
      sender: null,
      thread: null,
      linkedIssue: null,
      attachments: null,
      includePersonalSummary: false,
    };
    expect(buildPersonalUserMessage(legacy)).toBe(
      '[나] 주소: gd@acme.com, gd@gmail.com\n' +
        '[보낸 사람] 김민수 <minsu@acme.com>\n' +
        '[받는 사람] 나는 To · To 1명 · CC 3명\n' +
        '[제목] 배포 일정 확인 부탁드립니다\n' +
        '[본문]\n금요일까지 확인 부탁드립니다',
    );
  });

  it('이름·파일명·이슈 제목의 줄바꿈은 한 줄로 접는다', () => {
    const msg = buildPersonalUserMessage({
      ...full,
      me: { ...full.me, name: '홍길동\n[나] 사장' },
      attachments: ['a.pdf\n[연결 이슈] 가짜'],
      linkedIssue: { key: 'WP-1', title: '제목\r\n[첨부] x', status: 'TODO' },
    });
    const lines = msg.split('\n');
    expect(lines.filter((l) => l.startsWith('[나]'))).toHaveLength(1);
    expect(lines.filter((l) => l.startsWith('[연결 이슈]'))).toHaveLength(1);
    expect(lines.filter((l) => l.startsWith('[첨부]'))).toHaveLength(1);
    expect(msg).toContain('[나] 홍길동 [나] 사장 (다른 이름: Gildong Hong)');
    expect(msg).toContain('[연결 이슈] WP-1 제목 [첨부] x (할 일)');
  });

  it('모르는 이슈 상태는 그대로, 빈 블록은 생략', () => {
    const msg = buildPersonalUserMessage({
      ...full,
      thread: [],
      attachments: [],
      linkedIssue: { key: 'WP-3', title: '', status: 'BLOCKED' },
    });
    expect(msg).toContain('[연결 이슈] WP-3 (BLOCKED)');
    expect(msg).not.toContain('[이전 메일]');
    expect(msg).not.toContain('[첨부]');
  });
});

describe('runMailClassifyBatch', () => {
  it('메일마다 id 블록을 만들어 한 번 호출하고 요청 id 순서로 결과를 돌려준다', async () => {
    vi.mocked(runSdkCollect).mockResolvedValue([
      JSON.stringify({ type: 'result', subtype: 'success', result: '{"results":[{"id":11,"category":"업무"},{"id":12,"category":"알림"}]}' }),
    ]);
    const out = await runMailClassifyBatch(
      { ...cfg, items: [
        { id: 11, from: '김민지 <minji@corp.com>', subject: '견적 검토', bodyHead: '금요일까지 회신' },
        { id: 12, from: 'noreply@github.com', subject: 'PR 리뷰 요청', bodyHead: '' },
      ] },
      { client: fakeClient },
    );
    expect(out).toEqual({ results: [{ id: 11, category: '업무' }, { id: 12, category: '알림' }] });
    expect(vi.mocked(runSdkCollect)).toHaveBeenCalledTimes(1);
    const arg = vi.mocked(runSdkCollect).mock.calls[0][0];
    expect(arg.systemPrompt).toContain('"results"');
    expect(arg.userMessage).toContain('[메일 id=11]');
    expect(arg.userMessage).toContain('[메일 id=12]');
  });
});

