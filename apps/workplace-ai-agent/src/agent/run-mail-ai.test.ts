describe('buildPersonalUserMessage', () => {
  const base = {
    ...cfg,
    subject: '배포 일정 확인 부탁드립니다',
    fromAddress: 'minsu@acme.com',
    fromName: '김민수',
    body: '금요일까지 확인 부탁드립니다',
    autoGenerated: false,
    me: { addresses: ['gd@acme.com', 'gd@gmail.com'] },
    recipient: { myRole: 'TO' as const, toCount: 1, ccCount: 3 },
    includeNeedsReply: true,
    includePersonalSummary: false,
    includeCategory: false,
  };
  it('[나]·[보낸 사람]·[받는 사람]·[제목]·[본문] 순서로 조립', () => {
    expect(buildPersonalUserMessage(base)).toBe(
      '[나] 주소: gd@acme.com, gd@gmail.com\n' +
        '[보낸 사람] 김민수 <minsu@acme.com>\n' +
        '[받는 사람] 나는 To · To 1명 · CC 3명\n' +
        '[제목] 배포 일정 확인 부탁드립니다\n' +
        '[본문]\n금요일까지 확인 부탁드립니다',
    );
  });
  it('CC·없음·알 수 없음 표기', () => {
    expect(buildPersonalUserMessage({ ...base, recipient: { myRole: 'CC', toCount: 2, ccCount: 1 } })).toContain('[받는 사람] 나는 CC · To 2명 · CC 1명');
    expect(buildPersonalUserMessage({ ...base, recipient: { myRole: 'NONE', toCount: 2, ccCount: 0 } })).toContain('[받는 사람] 나는 To·CC 에 없음');
    expect(buildPersonalUserMessage({ ...base, recipient: { myRole: 'UNKNOWN', toCount: 0, ccCount: 0 } })).not.toContain('[받는 사람]');
  });
  it('이름이 없으면 주소만, 내 주소가 없으면 [나] 생략', () => {
    const msg = buildPersonalUserMessage({ ...base, fromName: '', me: { addresses: [] } });
    expect(msg).toContain('[보낸 사람] minsu@acme.com');
    expect(msg).not.toContain('[나]');
  });
});

