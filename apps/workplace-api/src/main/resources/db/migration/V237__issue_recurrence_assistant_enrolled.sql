-- V237 (WP-1119): 반복 저장이 비서를 담당에 직접 넣었는지 기억한다.
--
-- 반복을 저장하면 소유자의 AI 비서를 개인 작업의 담당으로 넣는다(V232, WP-989). 그 뒤 비서가 바뀌어 다시 저장하면 새 비서가 더해지지만
-- 예전 비서는 담당으로 남았다. 담당 행에는 누가 넣었는지가 소유자로만 남아 사람이 직접 넣은 담당과 가를 수 없으므로, 반복 행에
-- 「이 반복이 지금 실행 AI 를 담당에 넣었다」를 남긴다. 비서가 바뀔 때 이 값이 참이면 예전 비서를 담당에서 뺀다.
--
-- - 이 변경 전에 저장된 행은 누가 넣었는지 모르므로 거짓(빼지 않음)으로 둔다.
-- - 기본값이 있는 열 추가라 구 코드가 새 스키마에서 그대로 동작한다(롤링 배포 호환 — 구 코드가 쓴 행은 거짓).
ALTER TABLE issue_recurrence ADD COLUMN assistant_enrolled BOOLEAN NOT NULL DEFAULT FALSE;
