-- V271 (WP-1407): 같은 AI 의 반복 회차를 줄 세워 하나씩 보낸다.
--
-- 같은 AI 의 정각 회차 여럿이 같은 분에 함께 나가 한 모델 서버를 나눠 쓰다 시간 상한을 넘기고 연속 실패로 멈췄다. 스케줄러는 이제 같은 AI 에
-- 결과를 기다리는 실행(정기 회차·이어 처리·테스트 실행)이 있으면 그 AI 의 다른 정기 회차를 보내지 않고 미룬다(줄 대기).
--
-- - queued_at: 회차 시각이 됐는데 같은 AI 의 앞 회차가 끝나기를 기다리기 시작한 시각. 줄에 처음 선 순간에만 채워 작업 상태를 「대기 중」으로
--   한 번만 바꾸고, 회차를 보내거나 반복을 끄기·지우기·다시 저장하면 비운다. 보낼 때 줄 대기 시간을 로그로 남기는 데도 쓴다
--
-- nullable 열 추가라 구 코드가 새 스키마에서 그대로 동작한다(롤링 배포 호환 — 구 코드는 이 열을 모르고 쓰지 않는다).
ALTER TABLE issue_recurrence ADD COLUMN queued_at TIMESTAMPTZ;

COMMENT ON COLUMN issue_recurrence.queued_at IS '같은 AI 의 앞 회차가 끝나기를 기다리기 시작한 시각(WP-1407). 보내거나 끄면 비운다';
