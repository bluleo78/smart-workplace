package com.workplace.mail.service;

import com.workplace.global.tenant.TenantContext;
import com.workplace.global.util.Texts;
import com.workplace.mail.dto.EmailAccountResponse;
import com.workplace.mail.repository.EmailMessageRepository;
import com.workplace.mail.repository.EmailMessageRepository.InboxPushCandidate;
import com.workplace.mail.util.MailAddresses;
import com.workplace.mail.util.MailCategoryRules;
import com.workplace.mail.util.NeedsReplyRules;
import com.workplace.notify.push.PushCategory;
import com.workplace.notify.push.PushDispatcher;
import com.workplace.notify.push.PushMessage;
import java.util.List;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

/**
 * 메일 OS 푸시(WP-1739) — 동기화로 새 메일이 들어온 뒤, 계정의 알림 범위(notifyMode)에 걸리는지 판정해 웹 푸시를 보낸다.
 *
 * <p>발송은 best-effort: 푸시가 실패해도 동기화는 성공으로 끝나야 하므로 내부 try/catch 로 예외를 삼키고 warn 만 남긴다(PushDispatcher 도
 * 삼키지만 이중 방어가 설계 지침).
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class MailPushService {

  /** 푸시 후보 상한 — 한 번에 판정할 최대 메일 수(최신 {@code limit} 건, id 내림차순). */
  static final int CANDIDATE_LIMIT = 100;

  /** 제목·본문 절단 한계(코드포인트) — 푸시 알림 표시가 길어지지 않게 잘라 말줄임표를 붙인다. */
  static final int TEXT_LIMIT = 120;

  /** 푸시 TTL(초) — 하루. 오래된 새 메일 알림이 뒤늦게 뜨지 않도록 다른 메시지 푸시와 같은 값. */
  static final int MAIL_TTL_SECONDS = 86400;

  /** 알림 범위 — EmailAccountResponse.notifyMode() 값(기본 WORK, DB 기본값과 일치). */
  private static final String MODE_OFF = "OFF";

  private static final String MODE_ALL = "ALL";

  private static final String MODE_WORK = "WORK";

  private final EmailMessageRepository emailMessageRepository;
  private final PushDispatcher pushDispatcher;

  /**
   * 새 메일 푸시 판정(순수 함수) — 이 메일을 OS 푸시로 보낼지 정한다. 판정 순서(앞쪽이 이긴다, 순서가 결과를 바꾼다):
   *
   * <ol>
   *   <li>모드: OFF 면 무조건 false, ALL 은 분류·규칙 무관 true
   *   <li>WORK 일 때만 아래 규칙: ① 광고 제목(MailCategoryRules.isAd) → false ② 자동 발신(autoGenerated 저장값) →
   *       false ③ no-reply 발신(NeedsReplyRules.isAutoSender, 주소 판정) → false ④ 미분류(category null) →
   *       true(애매하면 보냄) ⑤ 업무 분류 → true, 그 밖(개인·알림·프로모션·뉴스레터) → false
   * </ol>
   *
   * <p>예상 밖 모드 문자열은 보수적으로 false — 발송을 건너뛰면 재설정으로 복구되지만, 원치 않은 발송은 되돌릴 수 없다. 알림을 꺼 둔 사용자에게 모르는 값 하나가
   * 발송을 허용하는 창이 되는 쪽이 위험하다(모르는 값은 잘못된 설정으로 보고 조용히 안 보낸다).
   *
   * @param notifyMode 알림 범위(OFF|ALL|WORK — null·예상 밖 값 허용)
   * @param category 유효 분류(없으면 null)
   * @param autoGenerated 자동 발신 저장 판정값(email_content.auto_generated)
   * @param subject 메일 제목(광고 표기 판정용, null 허용)
   * @param senderAddress 발신 주소(no-reply 판정용, null 허용)
   */
  public static boolean notifies(
      String notifyMode,
      String category,
      boolean autoGenerated,
      String subject,
      String senderAddress) {
    if (MODE_OFF.equals(notifyMode)) {
      return false;
    }
    if (MODE_ALL.equals(notifyMode)) {
      return true; // ALL 은 분류 무관 — 사용자가 모든 새 메일을 받겠다고 한 것
    }
    if (!MODE_WORK.equals(notifyMode)) {
      // 예상 밖 값 — 보수적으로 발송 안 함(위 javadoc 의 이유).
      return false;
    }
    // WORK 규칙 순서: 광고 → 자동 발신 → no-reply 발신 → 미분류 → 업무 분류
    if (MailCategoryRules.isAd(subject)) {
      return false;
    }
    if (autoGenerated) {
      return false;
    }
    if (NeedsReplyRules.isAutoSender(MailAddresses.normalize(senderAddress))) {
      return false;
    }
    if (category == null) {
      return true; // 미분류 — 분류가 늦어져도 새 메일 알림이 빠지지 않게 애매하면 보낸다
    }
    return EmailMessageRepository.WORK_CATEGORY.equals(category);
  }

  /**
   * 동기화 후 새로 들어온 안 읽은 메일을 판정해 푸시를 보낸다(후보 0건·판정 탈락·발송 실패 모두 성공으로 끝난다 — 예외는 삼키고 warn 로그).
   *
   * @param userId 계정 소유 사용자(푸시 수신자)
   * @param account 메일 계정 — {@code id}(범위)·{@code notifyMode}(판정) 사용
   * @param maxInboxId 동기화 전 받은편지함 최대 id({@link EmailMessageRepository#maxInboxId}) — 그 뒤부터가 「새 메일」
   */
  public void sendNewMail(long userId, EmailAccountResponse account, long maxInboxId) {
    try {
      // 푸시 식별자(테넌트) 확보 — sync 는 TenantContext 가 세팅된 스레드에서 실행되고, 없으면 푸시를 싣지 못하므로 방어적으로 스킵한다.
      long tenantId = TenantContext.require();
      List<InboxPushCandidate> targets =
          emailMessageRepository
              .findNewUnreadInbox(account.id(), maxInboxId, CANDIDATE_LIMIT)
              .stream()
              .filter(
                  c ->
                      notifies(
                          account.notifyMode(),
                          c.category(),
                          c.autoGenerated(),
                          c.subject(),
                          c.senderAddress()))
              .toList();
      if (targets.isEmpty()) {
        return; // 후보 0건(또는 전부 판정 탈락) — 발송 없이 조용히 종료
      }
      pushDispatcher.dispatchMail(List.of(userId), message(tenantId, account.id(), targets));
    } catch (Exception ex) {
      // best-effort 규칙 — 발송·조립·조회 어느 단계든 실패해도 동기화는 계속된다.
      log.warn("[push] 새 메일 푸시 실패 accountId={}: {}", account.id(), ex.getMessage());
    }
  }

  /**
   * 발송 단위 조립 — 후보 1건은 그 메일 그대로(제목=보낸 사람, 본문=제목, url 에 messageId), n건은 요약(새 메일 n통, url 은 계정 화면).
   * 제목·본문은 공통으로 {@link Texts#truncateCodePoints} 120자 절단. tag 는 계정 단위 — 여러 통이 같은 알림 한 줄로 교체된다.
   */
  private static PushMessage message(
      long tenantId, long accountId, List<InboxPushCandidate> targets) {
    InboxPushCandidate first = targets.get(0); // 목록은 id 내림차순 — 첫 통이 최신 메일
    String sender = senderOf(first);
    String title;
    String body;
    String url;
    if (targets.size() == 1) {
      title = sender;
      body = text(first.subject());
      url = "/mail/" + accountId + "?messageId=" + first.id();
    } else {
      title = "새 메일 " + targets.size() + "통";
      body = sender + " · " + text(first.subject());
      url = "/mail/" + accountId;
    }
    return new PushMessage(
        tenantId,
        PushCategory.MAIL,
        Texts.truncateCodePoints(title, TEXT_LIMIT),
        Texts.truncateCodePoints(body, TEXT_LIMIT),
        url,
        "mail-" + accountId,
        "high",
        MAIL_TTL_SECONDS);
  }

  /** 표시명 — 비어 있으면 주소로 대체하고(null·공백 모두), 둘 다 없으면 빈 문자열로 새지 않게 한다. */
  private static String senderOf(InboxPushCandidate c) {
    if (c.senderName() != null && !c.senderName().isBlank()) {
      return c.senderName();
    }
    return text(c.senderAddress());
  }

  /** null 을 빈 문자열로 — 본문·주소가 없어도 "null" 문자열이 푸시에 실리지 않게 한다. */
  private static String text(String s) {
    return s == null ? "" : s;
  }
}
