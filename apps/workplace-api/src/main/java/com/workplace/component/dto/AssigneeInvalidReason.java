package com.workplace.component.dto;

/**
 * 구성요소 기본 담당자를 자동 지정에 쓸 수 없는 이유(WP-1123). 설정 화면이 「구성원 아님」 하나로 뭉뚱그리지 않고 고칠 곳(계정 정지 해제 · 구성원 다시 추가)을
 * 알려 주도록 응답에 싣는다. 여러 이유가 겹치면 계정 정지가 먼저다 — 계정이 정지되면 구성원으로 되돌려도 여전히 쓸 수 없기 때문이다.
 */
public enum AssigneeInvalidReason {
  /** 이 워크스페이스에서 계정이 정지(비활성)됐다. */
  INACTIVE,
  /** 프로젝트 구성원이 아니다(빠졌거나 사용자가 없어짐). */
  NOT_MEMBER,
  /** 사람이 아니다(AI) — 담당자로 들어가는 순간 작업이 시작되는 부작용 때문에 자동 지정에서 뺀다. */
  NOT_HUMAN
}
