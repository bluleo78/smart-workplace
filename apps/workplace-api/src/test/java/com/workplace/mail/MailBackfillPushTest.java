/**
 * 본문 보충이 끝난 뒤 새 메일 푸시(WP-1739) 통합 테스트 — 자동 발송 판정값(email_content.auto_generated)은 본문을 받을 때 헤더
 * (List-Unsubscribe·Precedence: bulk 등)로 정해지므로, 동기화 직후가 아니라 보충이 끝난 뒤 판정해야 「업무 메일만(WORK)」에서 대량·자동
 * 발송이 빠진다.
 *
 * <p>비동기 진입점 {@code backfill(@Async)} 은 별도 스레드라 @Transactional 테스트의 미커밋 행을 보지 못해 아무것도 하지 않는다(보충 0건,
 * 후보 0건이라 발송도 없음). 그래서 sync 가 넘기는 것과 같은 경계로 동기 본체 {@code backfillNow(userId, accountId, push)} 를 직접
 * 불러 같은 트랜잭션에서 검증한다. 계정은 AI 분류를 켠다 — AI 가 꺼진 계정은 WORK 가 ALL 로 판정되어 자동 발송도 보내기 때문이다.
 */
@Transactional
class MailBackfillPushTest extends ExternalClientMockedTestBase {

  @RegisterExtension
  static GreenMailExtension greenMail =
      new MailTestGreenMail()
          .withConfiguration(
              GreenMailConfiguration.aConfig().withUser("box@test.local", "box@test.local", "pw"));

  @Autowired DSLContext dsl;
  @Autowired MailSyncService syncService;
  @Autowired MailBackfillService backfillService;
  @Autowired EmailAccountRepository accountRepo;
  @Autowired EmailMessageRepository messageRepo;
  @Autowired EncryptionService encryption;
  @Autowired MailAccountJobRepository jobRepo;

  /** 발송 단위 포착용 목 — 실푸시(HTTP)는 나가지 않는다. */
  @MockitoBean PushDispatcher pushDispatcher;

  /** AI 분류가 켜진 계정을 만들고 첫 동기화(발송 제외)를 마친다 — 다음 동기화부터 경계가 생긴다. */
  private long accountAfterFirstSync(long userId) {
    long accountId = MailTestSupport.insertAccount(accountRepo, encryption, userId, true);
    MailTestPorts.sendText("box@test.local", "alice@example.com", "기존 메일", "본문");
    greenMail.waitForIncomingEmail(1);
    syncService.sync(userId, accountId);
    // 비동기 보충이 진행 상태를 끝내길 기다리지 않고 가드 행을 지운다. 보충 스레드가 실행 핸들로 finish 해도 이 @Transactional 테스트의
    // 미커밋 행을 보지 못해 DB 행은 RUNNING 으로 남기 때문이다.
    jobRepo.delete(Kind.SYNC, accountId);
    return accountId;
  }

  /** 제목으로 찾은 메일의 자동 발송 판정값(email_content.auto_generated). */
  private Boolean autoGenerated(long accountId, String subject) {
    return dsl.select(EMAIL_CONTENT.AUTO_GENERATED)
        .from(EMAIL_MESSAGE)
        .join(EMAIL_CONTENT)
        .on(EMAIL_CONTENT.ID.eq(EMAIL_MESSAGE.CONTENT_ID))
        .where(EMAIL_MESSAGE.ACCOUNT_ID.eq(accountId))
        .and(EMAIL_CONTENT.SUBJECT.eq(subject))
        .fetchOne(EMAIL_CONTENT.AUTO_GENERATED);
  }

  /**
   * 대량 발송(List-Unsubscribe) 새 메일 — 동기화 직후엔 본문이 없어 auto_generated 가 아직 false 이므로 그때 판정하면 WORK 에서도
   * 보내진다. 동기화는 발송을 보충 뒤로 미루고, 보충이 auto_generated 를 true 로 만든 뒤 판정해 발송하지 않는다.
   */
  @Test
  void 대량_발송_새_메일은_본문_보충_뒤_판정해_업무_알림에서_빠진다() {
    long user = TestFixtures.createHuman(dsl);
    long accountId = accountAfterFirstSync(user);
    long boundary = messageRepo.maxInboxId(accountId);
    MailTestPorts.sendWithHeader(
        "box@test.local",
        "news@example.com",
        "이번 주 소식",
        "구독 본문",
        "List-Unsubscribe",
        "<mailto:unsub@example.com>");
    greenMail.waitForIncomingEmail(2);

    syncService.sync(user, accountId);

    // 동기화 직후 — 본문 미적재라 자동 발송 판정이 아직 false. 이때 보내면 대량 메일이 업무 알림으로 새어 나간다.
    assertThat(autoGenerated(accountId, "이번 주 소식")).isFalse();
    verify(pushDispatcher, never()).dispatchMail(any(), any());

    EmailAccountResponse account = accountRepo.findByIdAndUser(user, accountId).orElseThrow();
    backfillService.backfillNow(user, accountId, new NewMailPush(account, boundary));

    // 보충이 헤더로 자동 발송을 기록한 뒤 판정했으므로 WORK 에서 빠진다.
    assertThat(autoGenerated(accountId, "이번 주 소식")).isTrue();
    verify(pushDispatcher, never()).dispatchMail(any(), any());
  }

  /** 보통 새 메일 — 동기화 직후엔 보내지 않고, 본문 보충이 끝난 뒤 한 번 보낸다(대조군). */
  @Test
  void 보통_새_메일은_본문_보충이_끝난_뒤_한_번_보낸다() {
    long user = TestFixtures.createHuman(dsl);
    long accountId = accountAfterFirstSync(user);
    long boundary = messageRepo.maxInboxId(accountId);
    MailTestPorts.sendText("box@test.local", "bob@example.com", "회의 일정", "내일 10시");
    greenMail.waitForIncomingEmail(2);

    syncService.sync(user, accountId);
    verify(pushDispatcher, never()).dispatchMail(any(), any());

    EmailAccountResponse account = accountRepo.findByIdAndUser(user, accountId).orElseThrow();
    backfillService.backfillNow(user, accountId, new NewMailPush(account, boundary));

    ArgumentCaptor<PushMessage> message = ArgumentCaptor.forClass(PushMessage.class);
    verify(pushDispatcher, times(1)).dispatchMail(eq(List.of(user)), message.capture());
    assertThat(message.getValue().title()).isEqualTo("bob@example.com");
    assertThat(message.getValue().tag()).isEqualTo("mail-" + accountId);
  }

  /** 발송 정보 없이 부르는 보충(동기화가 아닌 경로·첫 동기화)은 푸시하지 않는다 — 새 메일 푸시는 동기화 경로에서만 나간다. */
  @Test
  void 발송_정보_없이_부른_보충은_푸시하지_않는다() {
    long user = TestFixtures.createHuman(dsl);
    long accountId = accountAfterFirstSync(user);
    MailTestPorts.sendText("box@test.local", "bob@example.com", "회의 일정", "내일 10시");
    greenMail.waitForIncomingEmail(2);
    syncService.sync(user, accountId);

    backfillService.backfillNow(user, accountId);

    assertThat(messageRepo.countMissingBody(accountId)).isZero(); // 보충은 그대로 한다
    verify(pushDispatcher, never()).dispatchMail(any(), any());
  }
}
