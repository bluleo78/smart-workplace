import org.mockito.ArgumentCaptor;

/**
 * 메일 OS 푸시(WP-1739) — 알림 범위 판정(notifies 순수 함수)과 새 메일 발송(sendNewMail) 규칙. 쿼리 자체는 Task 4 통합 테스트에서 함께
 * 검증한다.
 */
class MailPushServiceTest {

  /** 발송 시그니처 확인용 상수 — 수신자·계정·테넌트·경계 id. */
  private static final long USER_ID = 42L;

  private static final long ACCOUNT_ID = 7L;

  private static final long TENANT_ID = 99L;

  private static final long AFTER_ID = 5L;

  final EmailMessageRepository repository = mock(EmailMessageRepository.class);
  final PushDispatcher dispatcher = mock(PushDispatcher.class);
  final MailPushService service = new MailPushService(repository, dispatcher);

  @BeforeEach
  void setTenant() {
    // sendNewMail 은 발송 테넌트를 TenantContext 에서 얻는다 — sync 스레드는 TenantContext 가 세팅된 환경을 재현한다.
    TenantContext.set(TENANT_ID);
  }

  @AfterEach
  void clearTenant() {
    // 스레드 로컬 오염 방지 — 다음 테스트에 남지 않게 비운다.
    TenantContext.clear();
  }

  /** 알림 범위·계정 id 만 지정한 계정 응답 픽스처(그 외 필드는 판정에 무관). */
  private static EmailAccountResponse account(String notifyMode) {
    return new EmailAccountResponse(
        ACCOUNT_ID,
        "me@acme.com",
        "나",
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        null,
        false,
        null,
        MailProvider.IMAP,
        notifyMode);
  }

  /** 받은편지함 푸시 후보 픽스처 — 리포지토리가 반환하는(id 내림차순) 한 행. */
  private static InboxPushCandidate mail(
      long id, String senderName, String senderAddress, String subject, String category) {
    return new InboxPushCandidate(id, senderName, senderAddress, subject, category, false);
  }

  // ── notifies: 알림 범위 판정(순수 함수, 목 없음) ──────────────────────────

  @Test
  void notifies_offMode_neverNotifies() {
    // OFF 를 고른 계정은 분류·제목과 무관하게 절대 발송하지 않는다.
    assertThat(MailPushService.notifies("OFF", "업무", false, "주간 보고", "a@x.com")).isFalse();
    assertThat(MailPushService.notifies("OFF", null, false, null, null)).isFalse();
  }

  @Test
  void notifies_allMode_notifiesEvenPromotion() {
    // ALL 은 분류 무관 — 프로모션도 발송한다(1번 케이스).
    assertThat(MailPushService.notifies("ALL", "프로모션", false, "세일 안내", "shop@x.com")).isTrue();
  }

  @Test
  void notifies_workMode_workCategory_notifies() {
    assertThat(MailPushService.notifies("WORK", "업무", false, "회의 자료", "a@x.com")).isTrue();
  }

  @Test
  void notifies_workMode_uncategorized_notifies() {
    // 미분류(null)는 애매하면 보낸다 — 분류가 늦어져도 새 메일 알림이 빠지지 않게.
    assertThat(MailPushService.notifies("WORK", null, false, "제목", "a@x.com")).isTrue();
  }

  @Test
  void notifies_workMode_personalCategory_notNotifies() {
    assertThat(MailPushService.notifies("WORK", "개인", false, "제목", "a@x.com")).isFalse();
  }

  @Test
  void notifies_workMode_autoGenerated_notNotifies() {
    // 자동 발신(예약 발송·시스템) — 사람이 보낸 게 아니라면 업무 알림으로 띄우지 않는다.
    assertThat(MailPushService.notifies("WORK", "업무", true, "배포 완료", "ci@x.com")).isFalse();
  }

  @Test
  void notifies_workMode_adSubject_notNotifies() {
    // 광고 표기 제목((광고)…) — MailCategoryRules.isAd 규칙 재사용.
    assertThat(MailPushService.notifies("WORK", "업무", false, "(광고) 봄맞이 세일", "s@x.com")).isFalse();
  }

  @Test
  void notifies_workMode_noReplySender_notNotifies() {
    // no-reply 발신 — NeedsReplyRules.isAutoSender 규칙 재사용(주소로 판정).
    assertThat(MailPushService.notifies("WORK", "업무", false, "알림", "no-reply@x.com")).isFalse();
    // 대소문자가 섞인 주소도 발신 판정에 걸려야 한다(주소는 대소문자를 가리지 않는다).
    assertThat(MailPushService.notifies("WORK", "업무", false, "알림", "No-Reply@X.com")).isFalse();
  }

  @Test
  void notifies_unknownMode_notNotifies() {
    // 예상 밖 모드 문자열은 보수적으로 발송 안 함 — 원치 않는 발송은 되돌릴 수 없지만, 안 보낸 건 재설정으로 복구된다.
    assertThat(MailPushService.notifies("EVERYTHING", "업무", false, "제목", "a@x.com")).isFalse();
  }

  // ── sendNewMail: 후보 조회 → 판정 → 조립 → 발송 ──────────────────────────

  @Test
  void sendNewMail_noCandidates_doesNotDispatch() {
    // 후보 0건 — 발송 없이 조용히 반환(1번 케이스의 0건).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100)).thenReturn(List.of());

    service.sendNewMail(USER_ID, account("ALL"), AFTER_ID);

    verifyNoInteractions(dispatcher);
  }

  @Test
  void sendNewMail_offMode_withCandidates_doesNotDispatch() {
    // OFF 계정 — 후보가 있어도 판정이 전부 걸러 발송하지 않는다(1번 케이스의 서비스 경유).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(List.of(mail(11L, "김철수", "chulsoo@x.com", "회의 자료", "업무")));

    service.sendNewMail(USER_ID, account("OFF"), AFTER_ID);

    verifyNoInteractions(dispatcher);
  }

  @Test
  void sendNewMail_singleCandidate_buildsSingleMailFormat() {
    // 후보 1건 — 제목=보낸 사람, 본문=제목, url 에 messageId 를 붙인다(4번 케이스 단건).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(List.of(mail(11L, "김철수", "chulsoo@x.com", "회의 자료", "업무")));

    service.sendNewMail(USER_ID, account("ALL"), AFTER_ID);

    ArgumentCaptor<PushMessage> captor = ArgumentCaptor.forClass(PushMessage.class);
    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), captor.capture());
    PushMessage m = captor.getValue();
    assertThat(m.tenantId()).isEqualTo(TENANT_ID);
    assertThat(m.category()).isEqualTo(PushCategory.MAIL);
    assertThat(m.title()).isEqualTo("김철수");
    assertThat(m.body()).isEqualTo("회의 자료");
    assertThat(m.url()).isEqualTo("/mail/7?messageId=11");
    assertThat(m.tag()).isEqualTo("mail-7");
    assertThat(m.urgency()).isEqualTo("high");
    assertThat(m.ttlSeconds()).isEqualTo(86400);
  }

  @Test
  void sendNewMail_threeCandidates_buildsSummaryFormat() {
    // 후보 3건(id 내림차순 — 첫 통이 최신) — 제목=새 메일 3통, 본문=첫 통 정보, url 은 메시지 id 없음(4번 케이스 다건).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(
            List.of(
                mail(31L, "김철수", "chulsoo@x.com", "최신 제목", "업무"),
                mail(30L, "박민수", "minsu@x.com", "두 번째 제목", "업무"),
                mail(29L, null, "no-name@x.com", "세 번째 제목", null)));

    service.sendNewMail(USER_ID, account("ALL"), AFTER_ID);

    ArgumentCaptor<PushMessage> captor = ArgumentCaptor.forClass(PushMessage.class);
    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), captor.capture());
    PushMessage m = captor.getValue();
    assertThat(m.title()).isEqualTo("새 메일 3통");
    assertThat(m.body()).isEqualTo("김철수 · 최신 제목");
    assertThat(m.url()).isEqualTo("/mail/7");
    assertThat(m.tag()).isEqualTo("mail-7");
  }

  @Test
  void sendNewMail_workMode_filtersOutNonWork() {
    // WORK 모드 + 섞인 후보 — 업무만 남아 단건 형식으로 발송되는지(판정과 조립 연결 고리).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(
            List.of(
                mail(21L, "이영희", "younghee@x.com", "사내 공지", "개인"),
                mail(20L, "김철수", "chulsoo@x.com", "주간 보고", "업무")));

    service.sendNewMail(USER_ID, account("WORK"), AFTER_ID);

    ArgumentCaptor<PushMessage> captor = ArgumentCaptor.forClass(PushMessage.class);
    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), captor.capture());
    assertThat(captor.getValue().title()).isEqualTo("김철수");
    assertThat(captor.getValue().body()).isEqualTo("주간 보고");
  }

  @Test
  void sendNewMail_nullSenderName_titleFallsBackToAddress() {
    // senderName 이 null — 제목에 주소를 쓴다(5번 케이스).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(List.of(mail(11L, null, "chulsoo@x.com", "제목", "업무")));

    service.sendNewMail(USER_ID, account("ALL"), AFTER_ID);

    ArgumentCaptor<PushMessage> captor = ArgumentCaptor.forClass(PushMessage.class);
    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), captor.capture());
    assertThat(captor.getValue().title()).isEqualTo("chulsoo@x.com");
  }

  @Test
  void sendNewMail_blankSenderName_titleFallsBackToAddress() {
    // senderName 이 공백뿐 — 역시 주소로 대체한다(5번 케이스).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(List.of(mail(11L, "   ", "chulsoo@x.com", "제목", "업무")));

    service.sendNewMail(USER_ID, account("ALL"), AFTER_ID);

    ArgumentCaptor<PushMessage> captor = ArgumentCaptor.forClass(PushMessage.class);
    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), captor.capture());
    assertThat(captor.getValue().title()).isEqualTo("chulsoo@x.com");
  }

  @Test
  void sendNewMail_longTitleAndBody_truncatedToLimit() {
    // 제목 121자·본문 150자 — 둘 다 120 코드포인트 + 말줄임표로 절단된다(5번 케이스).
    String longName = "A".repeat(121);
    String longSubject = "B".repeat(150);
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(List.of(mail(11L, longName, "a@x.com", longSubject, "업무")));

    service.sendNewMail(USER_ID, account("ALL"), AFTER_ID);

    ArgumentCaptor<PushMessage> captor = ArgumentCaptor.forClass(PushMessage.class);
    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), captor.capture());
    assertThat(captor.getValue().title()).isEqualTo("A".repeat(120) + "…");
    assertThat(captor.getValue().body()).isEqualTo("B".repeat(120) + "…");
  }

  @Test
  void sendNewMail_dispatcherThrows_doesNotPropagate() {
    // dispatcher 가 예외를 던져도 sendNewMail 밖으로 전파하지 않는다 — 발송 실패가 동기화를 깨지 않게(6번 케이스, 이중 방어).
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenReturn(List.of(mail(11L, "김철수", "chulsoo@x.com", "제목", "업무")));
    doThrow(new RuntimeException("push down")).when(dispatcher).dispatchMail(any(), any());

    assertThatCode(() -> service.sendNewMail(USER_ID, account("ALL"), AFTER_ID))
        .doesNotThrowAnyException();

    verify(dispatcher).dispatchMail(eq(List.of(USER_ID)), any(PushMessage.class));
  }

  @Test
  void sendNewMail_repositoryThrows_doesNotPropagate() {
    // 예외 삼킴 규칙은 조회·조립까지 전체에 적용된다 — 발송은 best-effort 라서 어느 단계든 실패해도 호출자에겐 성공이다.
    when(repository.findNewUnreadInbox(ACCOUNT_ID, AFTER_ID, 100))
        .thenThrow(new RuntimeException("db down"));

    assertThatCode(() -> service.sendNewMail(USER_ID, account("ALL"), AFTER_ID))
        .doesNotThrowAnyException();

    verifyNoInteractions(dispatcher);
  }
}
